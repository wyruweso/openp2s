/**
 * The roots Azure VPN gateways are known to chain to.
 *
 * These ship with OpenP2S rather than coming from the system trust store,
 * because a system store follows browser policy, and that is not this client's
 * question. DigiCert Global Root CA left browser trust in April 2026 and
 * distributions are dropping it, while Microsoft still issues gateway
 * certificates under it. A client for one known service does better to name the
 * roots that service uses, which is also what Microsoft's own OpenVPN profiles do.
 *
 * Certificates in Certificate Transparency logs in November 2026 show:
 *
 *     DigiCert Global Root CA -> DigiCert SHA2 Secure Server CA
 *         -> *.vpn.azure.com
 *     DigiCert Global Root G2 -> Microsoft TLS G2 RSA CA
 *         -> <guid>.ln.vpn.azure.com
 *
 * The cost of this choice: a distribution update cannot withdraw these roots,
 * and if Azure moves to another root, connecting fails until OpenP2S is updated
 * or the user passes --ca. They expire in 2031 (Root CA) and 2038 (G2).
 *
 * Keeping this list is therefore this project's job:
 *
 * - Add a root as soon as gateway certificates are seen under one not listed here.
 * - Remove a root once no valid certificate under vpn.azure.com chains to it.
 * - If a root is distrusted for cause, such as a compromise, rather than on a
 *   planned schedule, remove it and release at once, and say so in the release
 *   notes. Gateways that still use it will stop working until they move or the
 *   user passes --ca, which is the right way to fail.
 *
 * The certificate name check is what identifies the gateway. These only decide
 * which authorities may vouch for that name.
 */

export interface AzureRoot {
  readonly name: string;
  /** SHA-256 of the certificate, lowercase hex. tests/ca.test.ts holds the PEM to it. */
  readonly sha256: string;
  readonly pem: string;
}

